def render_icon(name_or_emoji, classes="", size=None):
    """
    Menghasilkan elemen SVG vector yang bersih dan interaktif.
    Memiliki inactive/active state dan efek fill halus saat cursor hover.
    """
    key = str(name_or_emoji).strip()
    icon_name = ICON_ALIASES.get(key, key.lower().replace("_", "-"))
    
    path_data = SVG_PATHS.get(icon_name)
    if not path_data:
        # Fallback ke icon info atau default
        path_data = SVG_PATHS.get("info", '<circle cx="12" cy="12" r="10"/>')

    size_attr = f' width="{size}" height="{size}"' if size else ''
    cls = f"svg-icon {classes}".strip()

    svg_html = (
        f'<svg viewBox="0 0 24 24" class="{cls}"{size_attr} '
        f'fill="none" stroke="currentColor" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
        f'{path_data}'
        f'</svg>'
    )
    return Markup(svg_html)

